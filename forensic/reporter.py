from __future__ import annotations

import json
import shutil
import tempfile
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


def _json_safe(value):
    if isinstance(value, (str, int, float, bool)) or value is None:
        return value
    if isinstance(value, dict):
        return {str(k): _json_safe(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_json_safe(v) for v in value]
    return str(value)


def create_evidence_package(
    original_file: str | Path,
    file_hash: str,
    metadata: dict[str, Any],
    frames: list[dict[str, Any]],
    frame_manifest: list[dict[str, Any]],
    output_dir: str | Path,
    sampling_interval: float,
    jpeg_quality: int,
) -> Path:
    """
    Create a structured ZIP evidence package:
      original/
      frames/
      metadata/
      logs/
      manifest.json
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    case_dir = output_dir / "forensic_evidence"
    if case_dir.exists():
        shutil.rmtree(case_dir)
    (case_dir / "original").mkdir(parents=True)
    (case_dir / "frames").mkdir(parents=True)
    (case_dir / "metadata").mkdir(parents=True)
    (case_dir / "logs").mkdir(parents=True)

    original_file = Path(original_file)
    shutil.copy2(original_file, case_dir / "original" / original_file.name)

    (case_dir / "metadata" / "metadata.json").write_text(
        json.dumps(_json_safe(metadata), indent=2), encoding="utf-8"
    )
    (case_dir / "metadata" / "file_sha256.txt").write_text(
        file_hash + "\n", encoding="utf-8"
    )
    (case_dir / "metadata" / "frame_hash_manifest.json").write_text(
        json.dumps(_json_safe(frame_manifest), indent=2), encoding="utf-8"
    )

    for item in frames:
        frame_name = f"frame_{int(item['index']):06d}_{float(item['timestamp']):010.2f}s.jpg"
        # Imported lazily to keep the reporter focused on packaging.
        import cv2
        ok, encoded = cv2.imencode(
            ".jpg",
            item["frame"],
            [int(cv2.IMWRITE_JPEG_QUALITY), int(jpeg_quality)],
        )
        if ok:
            (case_dir / "frames" / frame_name).write_bytes(encoded.tobytes())

    now = datetime.now(timezone.utc).isoformat()
    processing_log = {
        "created_utc": now,
        "sampling_interval_seconds": sampling_interval,
        "jpeg_quality": jpeg_quality,
        "original_filename": original_file.name,
        "original_sha256": file_hash,
        "sampled_frame_count": len(frames),
        "note": "Generated by Digital Image Forensics Analysis Tool.",
    }
    (case_dir / "logs" / "processing_log.json").write_text(
        json.dumps(processing_log, indent=2), encoding="utf-8"
    )

    manifest = {
        "package_type": "digital_forensic_evidence",
        "created_utc": now,
        "original": {
            "filename": original_file.name,
            "sha256": file_hash,
        },
        "contents": {
            "original": f"original/{original_file.name}",
            "frames_directory": "frames/",
            "metadata": "metadata/metadata.json",
            "file_hash": "metadata/file_sha256.txt",
            "frame_hashes": "metadata/frame_hash_manifest.json",
            "processing_log": "logs/processing_log.json",
        },
    }
    (case_dir / "manifest.json").write_text(
        json.dumps(manifest, indent=2), encoding="utf-8"
    )

    zip_path = output_dir / "forensic_evidence_package.zip"
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for path in case_dir.rglob("*"):
            if path.is_file():
                archive.write(path, path.relative_to(case_dir))

    return zip_path
